-- ONLINE BAR: THE BUZZ - LIVE CITY INTELLIGENCE
-- Advanced event/location discovery engine with cinematic media support.

-- 1. BUZZ CATEGORIES (Dynamic Registry)
CREATE TABLE IF NOT EXISTS public.buzz_categories (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    label TEXT UNIQUE NOT NULL,
    icon TEXT, -- Lucide icon name
    is_active BOOLEAN DEFAULT true,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 2. BUZZ POSTS (The Discovery Nodes)
CREATE TABLE IF NOT EXISTS public.buzz_posts (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    title TEXT NOT NULL,
    slug TEXT UNIQUE NOT NULL,
    description TEXT,
    category_id UUID REFERENCES public.buzz_categories(id),
    status TEXT DEFAULT 'DRAFT', -- 'DRAFT', 'LIVE', 'TRENDING', 'ENDED', 'ARCHIVED'

    -- Geographical Intelligence
    latitude NUMERIC,
    longitude NUMERIC,
    address TEXT,
    area_zone TEXT, -- e.g. 'Westlands'

    -- Temporal Node
    start_at TIMESTAMP WITH TIME ZONE NOT NULL,
    end_at TIMESTAMP WITH TIME ZONE NOT NULL,

    -- Intelligence Signals
    trend_score INTEGER DEFAULT 0, -- 0-100
    is_featured BOOLEAN DEFAULT false,

    created_by UUID REFERENCES auth.users(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 3. BUZZ MEDIA (Cinematic Assets)
CREATE TABLE IF NOT EXISTS public.buzz_media (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    buzz_id UUID REFERENCES public.buzz_posts(id) ON DELETE CASCADE,
    media_type TEXT NOT NULL, -- 'IMAGE', 'VIDEO'
    url TEXT NOT NULL,
    thumbnail_url TEXT,
    sort_order INTEGER DEFAULT 0,
    caption TEXT,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

-- 4. BUZZ ENGAGEMENT (Real-time Signals)
CREATE TABLE IF NOT EXISTS public.buzz_engagement (
    id BIGINT PRIMARY KEY GENERATED BY DEFAULT AS IDENTITY,
    buzz_id UUID REFERENCES public.buzz_posts(id) ON DELETE CASCADE,
    event_type TEXT NOT NULL, -- 'VIEW', 'OPEN', 'SHARE', 'MAP_OPEN', 'DIRECTIONS'
    session_id TEXT,
    user_id UUID REFERENCES public.profiles(id),
    latitude NUMERIC,
    longitude NUMERIC,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT now()
);

