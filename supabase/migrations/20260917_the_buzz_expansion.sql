-- 6. Trend Score Automation Function
CREATE OR REPLACE FUNCTION public.calculate_buzz_trend_score(b_id UUID)
RETURNS VOID AS $$
DECLARE
    v_views INTEGER;
    v_actions INTEGER;
    v_score INTEGER;
BEGIN
    SELECT count(*) INTO v_views FROM public.buzz_engagement WHERE buzz_id = b_id AND event_type = 'VIEW';
    SELECT count(*) INTO v_actions FROM public.buzz_engagement WHERE buzz_id = b_id AND event_type IN ('SHARE', 'MAP_OPEN', 'DIRECTIONS');

    -- Algorithm: Actions weighted 3x views
    v_score := LEAST(100, (v_views * 1 + v_actions * 3) / 10);

    UPDATE public.buzz_posts SET trend_score = v_score WHERE id = b_id;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

-- 7. Security (RLS)
ALTER TABLE public.buzz_categories ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.buzz_posts ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.buzz_media ENABLE ROW LEVEL SECURITY;
ALTER TABLE public.buzz_engagement ENABLE ROW LEVEL SECURITY;

CREATE POLICY "Public read active buzz" ON public.buzz_posts FOR SELECT USING (status IN ('LIVE', 'TRENDING'));
CREATE POLICY "Admins full control buzz" ON public.buzz_posts FOR ALL TO authenticated USING (true);
CREATE POLICY "Public read categories" ON public.buzz_categories FOR SELECT USING (true);
CREATE POLICY "Public read media" ON public.buzz_media FOR SELECT USING (true);
