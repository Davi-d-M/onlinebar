    most_viewed_product_id BIGINT,
    most_searched_term TEXT,
    preferred_device TEXT,
    preferred_browser TEXT,
    top_traffic_source TEXT,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT now()
