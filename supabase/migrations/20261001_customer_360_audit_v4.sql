-- 5. AUTOMATED METRIC UPDATER (Trigger)
CREATE OR REPLACE FUNCTION public.sync_customer_aggregate_metrics()
RETURNS trigger AS $$
BEGIN
    INSERT INTO public.customer_aggregate_metrics (user_id)
    VALUES (NEW.user_id)
    ON CONFLICT (user_id) DO UPDATE SET
        total_sessions = (SELECT COUNT(*) FROM public.customer_sessions WHERE user_id = NEW.user_id),
        total_active_time_sec = (SELECT SUM(total_active_time_sec) FROM public.customer_sessions WHERE user_id = NEW.user_id),
        total_pages_viewed = (SELECT SUM(pages_viewed) FROM public.customer_sessions WHERE user_id = NEW.user_id),
        total_products_viewed = (SELECT SUM(products_viewed) FROM public.customer_sessions WHERE user_id = NEW.user_id),
        total_clicks = (SELECT SUM(clicks_count) FROM public.customer_sessions WHERE user_id = NEW.user_id),
        updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- 7. REAL-TIME TELEMETRY RPCs
CREATE OR REPLACE FUNCTION public.increment_session_active_time(sess_id UUID, inc_active_ms BIGINT, inc_dwell_ms BIGINT)
RETURNS VOID AS $$
BEGIN
    UPDATE public.customer_sessions
    SET total_active_time_sec = total_active_time_sec + (inc_active_ms / 1000),
        total_dwell_time_sec = total_dwell_time_sec + (inc_dwell_ms / 1000),
        updated_at = NOW()
    WHERE id = sess_id;
END;
$$ LANGUAGE plpgsql;

CREATE OR REPLACE FUNCTION public.increment_session_metric(sess_id UUID, metric_name TEXT, inc_val INTEGER)
RETURNS VOID AS $$
BEGIN
    EXECUTE format('UPDATE public.customer_sessions SET %I = %I + %L, updated_at = NOW() WHERE id = %L',
        metric_name, metric_name, inc_val, sess_id);
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_sync_customer_metrics ON public.customer_sessions;
CREATE TRIGGER tr_sync_customer_metrics
    AFTER UPDATE OF user_id, total_active_time_sec, pages_viewed ON public.customer_sessions
    FOR EACH ROW EXECUTE PROCEDURE public.sync_customer_aggregate_metrics();

-- 6. RPC FOR BATCH UPLOAD (Performance Node)
CREATE OR REPLACE FUNCTION public.log_event_batch(p_events JSONB)
RETURNS VOID AS $$
DECLARE
    v_event JSONB;
BEGIN
    FOR v_event IN SELECT * FROM jsonb_array_elements(p_events)
    LOOP
        INSERT INTO public.session_forensics (
            session_id,
            action_type,
            page_url,
            metadata,
            timestamp
        ) VALUES (
            (v_event->>'session_id')::UUID,
            v_event->>'action_type',
            v_event->>'page_url',
            v_event->'metadata',
            (v_event->>'timestamp')::TIMESTAMP WITH TIME ZONE
        );
    END LOOP;
END;
$$ LANGUAGE plpgsql;

