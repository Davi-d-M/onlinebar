CREATE OR REPLACE VIEW public.financial_ledger AS
SELECT
    le.id::text as legacy_id,
    le.id,
    lt.reference_id as order_id,
    la.type as entry_type,
    le.amount,
    lt.description,
    le.created_at
FROM public.ledger_entries le
JOIN public.ledger_transactions lt ON le.transaction_id = lt.id
JOIN public.ledger_accounts la ON le.account_id = la.id;

