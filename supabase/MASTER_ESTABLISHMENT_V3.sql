-- 12. BUZZ ENGINE (City Pulse)
CREATE OR REPLACE VIEW public.buzz_metrics AS
SELECT
    zone_name,
    active_visitors,
    active_orders,
    (active_visitors * 0.4 + active_orders * 0.6) as buzz_score,
    CASE
        WHEN (active_visitors * 0.4 + active_orders * 0.6) > 80 THEN 'BUZZING'
        WHEN (active_visitors * 0.4 + active_orders * 0.6) > 50 THEN 'BUSY'
        WHEN (active_visitors * 0.4 + active_orders * 0.6) > 20 THEN 'ACTIVE'
        ELSE 'QUIET'
    END as buzz_status
FROM public.neighborhood_trends;

-- 13. TRIGGERS & AUTOMATION

-- A. Auth to Profile Sync (Idempotent Hardening)
CREATE OR REPLACE FUNCTION public.handle_new_user()
RETURNS trigger AS $$
BEGIN
  INSERT INTO public.profiles (id, email, full_name, phone_number, address)
  VALUES (
    new.id,
    new.email,
    NULLIF(new.raw_user_meta_data->>'full_name', ''),
    NULLIF(new.raw_user_meta_data->>'phone_number', ''),
    NULLIF(new.raw_user_meta_data->>'address', '')
  )
  ON CONFLICT (id) DO UPDATE SET
    email = EXCLUDED.email,
    full_name = COALESCE(public.profiles.full_name, EXCLUDED.full_name),
    phone_number = COALESCE(public.profiles.phone_number, EXCLUDED.phone_number),
    address = COALESCE(public.profiles.address, EXCLUDED.address);
  RETURN new;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

DROP TRIGGER IF EXISTS on_auth_user_created ON auth.users;
CREATE TRIGGER on_auth_user_created
  AFTER INSERT ON auth.users
  FOR EACH ROW EXECUTE PROCEDURE public.handle_new_user();

-- B. Sync Ledger Balance
CREATE OR REPLACE FUNCTION public.sync_ledger_balance()
RETURNS TRIGGER AS $$
BEGIN
    UPDATE public.ledger_accounts
    SET balance = balance + NEW.amount
    WHERE id = NEW.account_id;
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS tr_sync_balance ON public.ledger_entries;
CREATE TRIGGER tr_sync_balance
AFTER INSERT ON public.ledger_entries
FOR EACH ROW EXECUTE PROCEDURE public.sync_ledger_balance();

