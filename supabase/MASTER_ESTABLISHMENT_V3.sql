-- Legacy Compatibility View (If needed)
DO $$ BEGIN
    IF EXISTS (SELECT 1 FROM information_schema.tables WHERE table_schema = 'public' AND table_name = 'financial_ledger' AND table_type = 'BASE TABLE') THEN
